assert.equal(pl, "#EXTM3U\n#EXT-X-KEY:METHOD=AES-128,URI=\"R(https://x.lechange.com/live/key.bin)\"\nR(https://x.lechange.com/live/seg1.ts)\nR(https://y.lechange.com/seg2.ts)\n");
